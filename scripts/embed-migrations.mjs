// Reads drizzle-kit output (src/db/migrations/*.sql + meta/_journal.json) and emits
// src/db/migrations.gen.ts so migrations ship inside the JS bundle — no folder to
// resolve at runtime under npx/bunx. Run after every `npm run db:generate`.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "src/db/migrations");
const journal = JSON.parse(readFileSync(join(migrationsDir, "meta/_journal.json"), "utf8"));

const entries = journal.entries.map((e) => {
  const sql = readFileSync(join(migrationsDir, `${e.tag}.sql`), "utf8");
  const statements = sql
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { idx: e.idx, tag: e.tag, statements };
});

const out = `// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit.
// Regenerate with: npm run db:generate
export interface Migration {
  idx: number;
  tag: string;
  statements: string[];
}

export const migrations: Migration[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join(root, "src/db/migrations.gen.ts"), out);
console.log(`embedded ${entries.length} migration(s) into src/db/migrations.gen.ts`);
